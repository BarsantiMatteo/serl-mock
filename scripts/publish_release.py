"""
Publish a generated mock dataset into a shared sources folder (optional).

Not needed to use serl-mock: the generate scripts write data/mock/<output_label>/
and that folder is all a user needs. This script is for keeping several
tools on one machine reading the same data from one place, laid out like
the TRE's ~/shared/sources/:

  <sources root>/editions/<name>/   an edition run (generate_mock_data.py,
                                    generate_next_edition.py)
  <sources root>/raw/<name>/        a raw run (generate_raw_data.py)

It copies data/mock/<dataset>/ there (with the bank and school holiday CSVs
from data/reference/, which sit next to an edition's files in the TRE), and
writes two files next to the data:

  RELEASE.md    what this release is, for people
  release.json  the same, for tools: name, kind, source dataset, serl-mock
                commit, date, and every file with its size and SHA-256

A release is never changed: if <name> already exists the script stops.
Regenerating a dataset and publishing it again needs a new name, or
deleting the old release first.

  uv run python scripts/publish_release.py --dataset edition08_2024_N1000
  uv run python scripts/publish_release.py --dataset raw_from_edition08 --kind raw
  uv run python scripts/publish_release.py --dataset edition08_gappy --name mock_edition08_gappy_v2

Sources root: --sources-root, else $SERL_SOURCES_ROOT, else
../_serl_shared/sources next to this repo. Default name: mock_<dataset>.
Uses the standard library only.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
import shutil
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
MOCK_DIR = REPO_ROOT / "data" / "mock"
REFERENCE_DIR = REPO_ROOT / "data" / "reference"
HOLIDAY_FILES = ("uk_bank_holidays_england_wales_scotland.csv",
                 "uk_school_holidays_england_wales_scotland.csv")
KIND_FOLDER = {"edition": "editions", "raw": "raw"}


def default_sources_root() -> Path:
    return Path(os.getenv("SERL_SOURCES_ROOT") or REPO_ROOT.parent / "_serl_shared" / "sources")


def git_commit(repo: Path) -> str | None:
    """Short commit of `repo`, '-dirty' if it has uncommitted changes; None without git."""
    try:
        commit = subprocess.run(["git", "-C", str(repo), "rev-parse", "--short", "HEAD"],
                                capture_output=True, text=True, check=True).stdout.strip()
        dirty = subprocess.run(["git", "-C", str(repo), "status", "--porcelain"],
                               capture_output=True, text=True, check=True).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return None
    return f"{commit}-dirty" if dirty else commit


def sha256(path: Path, chunk: int = 8 * 1024 * 1024) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        while block := f.read(chunk):
            h.update(block)
    return h.hexdigest()


def file_list(folder: Path) -> list[dict]:
    return [
        {"path": p.relative_to(folder).as_posix(), "bytes": p.stat().st_size, "sha256": sha256(p)}
        for p in sorted(folder.rglob("*"))
        if p.is_file() and p.name not in ("RELEASE.md", "release.json")
    ]


def release_markdown(meta: dict) -> str:
    lines = [
        f"# {meta['name']}",
        "",
        f"Mock SERL data, **not real**: a {meta['kind']} dataset generated by serl-mock and",
        "published here unchanged. Its numbers say only whether a pipeline works.",
        "",
        "| | |",
        "|---|---|",
        f"| Kind | {meta['kind']} |",
        f"| Source | serl-mock `data/mock/{meta['source']['dataset']}/` |",
        f"| serl-mock commit | `{meta['source']['commit'] or 'unknown'}` |",
        f"| Generator config | `{meta['source']['config'] or 'not recorded'}` |",
        f"| Holiday CSVs added from data/reference/ | {', '.join(meta['added_files']) or 'none'} |",
        f"| Published | {meta['published_at']} |",
        f"| Files | {len(meta['files'])}, {sum(f['bytes'] for f in meta['files']) / 1e6:,.1f} MB |",
        "",
        "Every file's size and SHA-256 is in `release.json`. This folder is never",
        "changed: a new run is published under a new name.",
        "",
    ]
    return "\n".join(lines)


def publish(dataset: str, name: str, kind: str, sources_root: Path) -> Path:
    src = MOCK_DIR / dataset
    if not src.is_dir():
        raise FileNotFoundError(f"No dataset at {src} -- generate it first (scripts/generate_*.py).")
    target = sources_root / KIND_FOLDER[kind] / name
    if target.exists():
        raise FileExistsError(f"{target} already exists -- a release is never changed; "
                              "use another --name, or delete it first.")
    partial = target.with_name(target.name + ".partial")
    if partial.exists():
        shutil.rmtree(partial)

    print(f"[publish] {src} -> {target}")
    shutil.copytree(src, partial)
    added = []
    if kind == "edition":
        for fname in HOLIDAY_FILES:
            ref = REFERENCE_DIR / fname
            if ref.is_file() and not (partial / fname).exists():
                shutil.copy2(ref, partial / fname)
                added.append(fname)

    config = partial / "mock_internal" / "serl_mock_config.yaml"
    print("[publish] checksums ...")
    meta = {
        "name": name,
        "kind": kind,
        "tool": "serl-mock",
        "source": {
            "dataset": dataset,
            "commit": git_commit(REPO_ROOT),
            "config": config.relative_to(partial).as_posix() if config.is_file() else None,
        },
        "added_files": added,
        "published_at": datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC"),
        "files": file_list(partial),
    }
    (partial / "release.json").write_text(json.dumps(meta, indent=2), encoding="utf-8")
    (partial / "RELEASE.md").write_text(release_markdown(meta), encoding="utf-8")
    partial.rename(target)
    print(f"[publish] {len(meta['files'])} file(s) -> {target}")
    return target


def main(argv=None) -> int:
    p = argparse.ArgumentParser(description=__doc__.strip().splitlines()[0])
    p.add_argument("--dataset", required=True, help="folder under data/mock/, e.g. edition08_2024_N1000")
    p.add_argument("--name", help="release folder name (default: mock_<dataset>)")
    p.add_argument("--kind", choices=sorted(KIND_FOLDER),
                   help="edition or raw (default: raw if the dataset name starts with raw_)")
    p.add_argument("--sources-root", type=Path,
                   help="default: $SERL_SOURCES_ROOT, else ../_serl_shared/sources")
    args = p.parse_args(argv)
    kind = args.kind or ("raw" if args.dataset.startswith("raw_") else "edition")
    try:
        publish(args.dataset, args.name or f"mock_{args.dataset}", kind,
                args.sources_root or default_sources_root())
    except (FileNotFoundError, FileExistsError) as e:
        print(f"[publish] {e}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
